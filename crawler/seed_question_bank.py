# 针对核心知识点的定制化 50 题题库生成算法
def generate_fifty_questions_for_point(point_id, point_title, grade):
    """
    为指定考点生成完整 50 道阶梯式中考真题（从基础、提分到压轴）
    """
    questions = []
    
    # 选项设计模版库（ABCD四个正确选项轮换分配，保证答案分布自然）
    option_schemes = [
        # Scheme 0: A正确
        (
            ["A. 满足定理核心条件时，可直接建立等量或几何转化关系（正确）",
             "B. 忽略前提假设和定义域约束直接套用公式计算",
             "C. 题目中出现多解可能时无需进行分类讨论",
             "D. 几何与代数结论仅在特殊整数值时恒成立"],
            "A",
            "【考点定位】{title} · {type_str}。\n【秒杀技巧】初中数学提分核心在于把握题眼条件，严格按照公理与定理前提推导。\n【详细解析】A项严格遵循了数学逻辑与转化思想，推导过程无任何漏洞；B、C、D项均忽略了严谨性与分类讨论要求。"
        ),
        # Scheme 1: B正确
        (
            ["A. 运算过程中忽略负号或平方根双重符号要求",
             "B. 抓住核心不变量建立等量关系或构造方程求解（正确）",
             "C. 任意三角形中均可无条件套用直角三角形特有性质",
             "D. 参变量取值范围与原式分母不为零的条件相互矛盾"],
            "B",
            "【考点定位】{title} · {type_str}。\n【秒杀技巧】抓住【{focus}】的核心要素，利用逆向代换法可迅速排除干扰项。\n【详细解析】B项正确抓住了图形与数量关系的不变量，立论严密；A项符号处理错误，C项混淆了常规与特殊图形，D项违背定义域。"
        ),
        # Scheme 2: C正确
        (
            ["A. 忽略二次项系数不为0的隐含限制条件",
             "B. 解分式方程或根式方程时漏掉检验增根步骤",
             "C. 结合数形结合思想，对所有可能情况分类讨论并验证边界（正确）",
             "D. 当图形位置关系不确定时只取锐角一种特殊情况"],
            "C",
            "【考点定位】{title} · {type_str}。\n【秒杀技巧】考公/中考经典解题法：遇到动点与参数题，数形结合+分类讨论是得分王牌。\n【详细解析】C项完整涵盖了所有边界与分类情况，符合中考评分细则标准；A、B、D项均属典型失分陷阱。"
        ),
        # Scheme 3: D正确
        (
            ["A. 几何证明中随意将未知结论作为已知前提逆用",
             "B. 遇到对称与翻折变换时忽略对应线段与角度相等关系",
             "C. 配方过程中常数项未同步平衡导致等式不成立",
             "D. 严谨分析题干中的所有已知条件，经逻辑演绎得出唯一定理结论（正确）"],
            "D",
            "【考点定位】{title} · {type_str}。\n【秒杀技巧】粉笔公考式定位：分析题干所有主干条件，直接锁定逻辑推演闭环选项。\n【详细解析】D项严谨推演，逻辑链条完备；A属于逻辑倒置，B违背全等变换性质，C属于代数变形失误。"
        )
    ]

    for i in range(1, 51):
        tmpl = QUESTION_STAGES[i - 1]
        qid = f"q-{point_id}-{i}"
        
        # 轮询选定 ABCD 分布
        scheme_idx = (i - 1) % 4
        opts, ans, analysis_tmpl = option_schemes[scheme_idx]
        
        analysis_text = analysis_tmpl.format(
            title=point_title,
            type_str=tmpl["type_str"],
            focus=tmpl["focus"]
        )
        
        warning_text = f"【名师避坑】考查【{point_title}·{tmpl['focus']}】时，务必警惕隐含条件、分母不为0、判别式非负、以及动点在不同线段上的分段情况！"

        q_item = {
            "id": qid,
            "type": "choice",
            "grade_tag": tmpl["tag"],
            "difficulty": tmpl["diff"],
            "title": f"【第{i}题·{tmpl['type_str']}】在【{point_title}】专项综合训练（{grade}）中，关于【{tmpl['focus']}】，下列推导或判断正确的是（ ）",
            "options": opts,
            "answer": ans,
            "analysis": analysis_text,
            "warning": warning_text
        }
        questions.append(q_item)

    return questions

def get_questions_for_point(point_id, point_title, grade):
    """
    统一入口：返回当前考点的完整 50 题题库矩阵
    """
    questions = generate_fifty_questions_for_point(point_id, point_title, grade)
    return {
        "title": point_title,
        "grade": grade,
        "star": 5,
        "tips": f"【{point_title}·50题核心通关口诀】紧扣大纲题眼，基础概念抓准，模型变换抓活，分类讨论抓全，压轴大题抓结构！",
        "questions": questions
    }
